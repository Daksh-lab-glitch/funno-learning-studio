      where classroom_id is null;
    update public.resources set classroom_id = legacy_classroom_id where classroom_id is null;
    update public.assignments set classroom_id = legacy_classroom_id where classroom_id is null;
    update public.quizzes set classroom_id = legacy_classroom_id where classroom_id is null;
    update public.quiz_answer_keys set classroom_id = legacy_classroom_id where classroom_id is null;
    update public.announcements set classroom_id = legacy_classroom_id where classroom_id is null;
  end if;
end;
$$;

