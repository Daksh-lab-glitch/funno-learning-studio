-- Multi-institution classrooms, school/course enrollment, and teacher help chat.
-- Existing classroom rows are preserved and placed into the existing teacher's
-- first classroom so the migration is safe for an already-running project.

create table public.institutions (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 180),
  institution_type text not null check (institution_type in ('school', 'university', 'other')),
  created_by uuid not null default auth.uid() references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table public.classrooms (
  id bigint generated by default as identity primary key,
  institution_id bigint not null references public.institutions(id) on delete cascade,
  teacher_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 140),
  education_level text not null check (education_level in ('school', 'university', 'other')),
  grade text check (grade is null or char_length(grade) <= 80),
  course text check (course is null or char_length(course) <= 140),
  join_code text not null unique default upper(substr(md5(random()::text || clock_timestamp()::text), 1, 8)),
  created_at timestamptz not null default now(),
  constraint classrooms_school_or_uni_fields check (
    (education_level = 'school' and grade is not null)
    or (education_level = 'university' and course is not null)
    or education_level = 'other'
  )
);
create index classrooms_teacher_id_idx on public.classrooms(teacher_id);
create index classrooms_institution_id_idx on public.classrooms(institution_id);

