-- A caller's signup metadata never grants the teacher role. New users select
-- their account type in the UI and may promote only their own account by RPC.
create or replace function private.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.user_profiles(id, email, display_name, role)
  values (new.id, coalesce(new.email, ''),
    coalesce(nullif(left(new.raw_user_meta_data ->> 'display_name', 100), ''), split_part(coalesce(new.email, 'Classroom member'), '@', 1)),
    'student');
  return new;
end;
$$;

