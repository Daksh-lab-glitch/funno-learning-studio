create policy funno_class_files_read on storage.objects for select to authenticated
  using (
    bucket_id = 'classroom-files'
    and (
      (storage.foldername(name))[1] = 'resources'
      or (
        (storage.foldername(name))[1] = 'submissions'
        and (
          (select private.is_teacher())
          or exists (
            select 1 from public.students s
            where s.id::text = (storage.foldername(name))[2]
              and s.auth_user_id = (select auth.uid())
          )
        )
      )
    )
  );
create policy funno_class_files_insert on storage.objects for insert to authenticated
  with check (
    bucket_id = 'classroom-files'
    and (
      ((storage.foldername(name))[1] = 'resources' and (select private.is_teacher()))
      or (
        (storage.foldername(name))[1] = 'submissions'
        and exists (
          select 1 from public.students s
          where s.id::text = (storage.foldername(name))[2]
            and s.auth_user_id = (select auth.uid())
        )
      )
    )
  );
create policy funno_class_files_delete on storage.objects for delete to authenticated
