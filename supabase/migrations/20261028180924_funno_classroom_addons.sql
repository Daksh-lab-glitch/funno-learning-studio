-- Assignment work/review, teacher attendance, announcements, and private uploads.

alter table public.resources
  add column storage_path text,
  add column file_name text check (file_name is null or char_length(file_name) <= 255),
  add column file_size_bytes bigint check (file_size_bytes is null or file_size_bytes between 0 and 10485760);

alter table public.assignments
  add column max_points integer not null default 100 check (max_points between 1 and 1000);

alter table public.submissions
  add column status text not null default 'submitted' check (status in ('submitted', 'graded')),
  add column grade numeric(7,2) check (grade is null or grade between 0 and 1000),
  add column teacher_feedback text check (teacher_feedback is null or char_length(teacher_feedback) <= 1000),
  add column file_path text,
  add column file_name text check (file_name is null or char_length(file_name) <= 255),
  add column submitted_at timestamptz not null default now(),
  add column graded_at timestamptz;
create index submissions_assignment_status_idx on public.submissions(assignment_id, status, submitted_at desc);
create unique index submissions_assignment_student_unique on public.submissions(assignment_id, student_id);

drop policy if exists submissions_update_own on public.submissions;
create policy submissions_update_own_ungraded on public.submissions for update to authenticated
  using (grade is null and teacher_feedback is null and status = 'submitted' and exists (
    select 1 from public.students s where s.id = student_id and s.auth_user_id = (select auth.uid())
  ))
  with check (grade is null and teacher_feedback is null and graded_at is null and status = 'submitted' and exists (
    select 1 from public.students s where s.id = student_id and s.auth_user_id = (select auth.uid()) and s.name = student_name
  ) and (file_path is null or file_path like ('submissions/' || student_id::text || '/%')));
drop policy if exists submissions_insert_own on public.submissions;
create policy submissions_insert_own on public.submissions for insert to authenticated
  with check (
    grade is null and teacher_feedback is null and graded_at is null and status = 'submitted'
    and exists (select 1 from public.students s where s.id = student_id and s.auth_user_id = (select auth.uid()) and s.name = student_name)
    and (file_path is null or file_path like ('submissions/' || student_id::text || '/%'))
  );
create policy submissions_teacher_update on public.submissions for update to authenticated
  using ((select private.is_teacher())) with check ((select private.is_teacher()));

create or replace function private.guard_submission_update()
returns trigger language plpgsql set search_path = ''
as $$
begin
  if (select private.is_teacher()) then return new; end if;
  if old.student_id is distinct from new.student_id
    or old.assignment_id is distinct from new.assignment_id
    or old.student_name is distinct from new.student_name
    or old.grade is distinct from new.grade
    or old.teacher_feedback is distinct from new.teacher_feedback
    or old.status is distinct from new.status
    or old.graded_at is distinct from new.graded_at then
    raise exception 'Students cannot change submission ownership or grading fields';
  end if;
  if old.grade is not null or old.status <> 'submitted' then
    raise exception 'A graded submission cannot be edited';
  end if;
  if new.file_path is not null and new.file_path not like ('submissions/' || new.student_id::text || '/%') then
    raise exception 'Submission file path does not belong to this learner';
  end if;
  return new;
end;
$$;
revoke all on function private.guard_submission_update() from public, anon, authenticated;
drop trigger if exists guard_funno_submission_update on public.submissions;
create trigger guard_funno_submission_update before update on public.submissions
for each row execute function private.guard_submission_update();

create table public.attendance_entries (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(id) on delete cascade,
  class_date date not null default current_date,
  status text not null check (status in ('present', 'absent', 'late', 'excused')),
  note text check (note is null or char_length(note) <= 500),
  marked_by uuid not null default auth.uid() references auth.users(id),
  created_at timestamptz not null default now(),
  unique (student_id, class_date)
);
create index attendance_date_student_idx on public.attendance_entries(class_date desc, student_id);
alter table public.attendance_entries enable row level security;
create policy attendance_read_own_or_teacher on public.attendance_entries for select to authenticated
  using ((select private.is_teacher()) or exists (
    select 1 from public.students s where s.id = student_id and s.auth_user_id = (select auth.uid())
  ));
create policy attendance_teacher_insert on public.attendance_entries for insert to authenticated
  with check ((select private.is_teacher()));
create policy attendance_teacher_update on public.attendance_entries for update to authenticated
  using ((select private.is_teacher())) with check ((select private.is_teacher()));
create policy attendance_teacher_delete on public.attendance_entries for delete to authenticated
  using ((select private.is_teacher()));
grant select, insert, update, delete on public.attendance_entries to authenticated;
revoke all on public.attendance_entries from anon;

create table public.announcements (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 160),
  body text not null check (char_length(body) between 1 and 3000),
  published_at timestamptz not null default now(),
  reminder_at timestamptz,
  created_by uuid not null default auth.uid() references auth.users(id),
  created_at timestamptz not null default now()
);
create index announcements_publish_time_idx on public.announcements(published_at desc);
alter table public.announcements enable row level security;
create policy announcements_read_published_or_teacher on public.announcements for select to authenticated
  using ((select private.is_teacher()) or published_at <= now());
create policy announcements_teacher_insert on public.announcements for insert to authenticated
  with check ((select private.is_teacher()) and created_by = (select auth.uid()));
create policy announcements_teacher_update on public.announcements for update to authenticated
  using ((select private.is_teacher())) with check ((select private.is_teacher()));
create policy announcements_teacher_delete on public.announcements for delete to authenticated
  using ((select private.is_teacher()));
grant select, insert, update, delete on public.announcements to authenticated;
revoke all on public.announcements from anon;
grant usage, select on sequence public.attendance_entries_id_seq, public.announcements_id_seq to authenticated;

