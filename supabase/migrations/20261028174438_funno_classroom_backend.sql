-- Funno Learning Studio classroom schema.
-- The first account created in a fresh project becomes the classroom teacher.
-- Every later signup is a student until a teacher promotes/links the account.

create schema if not exists private;
revoke all on schema private from public, anon;
grant usage on schema private to authenticated;

create table public.user_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  display_name text not null default 'Classroom member' check (char_length(display_name) between 1 and 100),
  role text not null default 'student' check (role in ('teacher', 'student')),
  created_at timestamptz not null default now()
);
create unique index user_profiles_one_teacher on public.user_profiles ((role)) where role = 'teacher';

create table public.students (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 100),
  attendance numeric(5,2) not null check (attendance between 0 and 100),
  assessment numeric(5,2) not null check (assessment between 0 and 100),
  participation numeric(5,2) not null check (participation between 0 and 100),
  auth_user_id uuid unique references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table public.resources (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 140),
  type text not null default 'lesson' check (type in ('lesson', 'link', 'file')),
  url text,
  description text check (description is null or char_length(description) <= 500),
  created_by uuid not null default auth.uid() references auth.users(id),
  created_at timestamptz not null default now()
);

create table public.assignments (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 160),
  description text check (description is null or char_length(description) <= 2000),
  due_date date,
  created_by uuid not null default auth.uid() references auth.users(id),
  created_at timestamptz not null default now()
);

create table public.submissions (
  id bigint generated by default as identity primary key,
  assignment_id bigint not null references public.assignments(id) on delete cascade,
  student_id bigint not null references public.students(id) on delete cascade,
  student_name text not null check (char_length(student_name) between 1 and 100),
  response text not null default '',
  created_at timestamptz not null default now(),
  unique (assignment_id, student_id)
);

create table public.quizzes (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 140),
  questions jsonb not null check (jsonb_typeof(questions) = 'array' and jsonb_array_length(questions) between 1 and 20),
  created_by uuid not null default auth.uid() references auth.users(id),
  created_at timestamptz not null default now()
);

create table public.quiz_results (
  id bigint generated by default as identity primary key,
  quiz_id bigint not null references public.quizzes(id) on delete cascade,
  student_id bigint not null references public.students(id) on delete cascade,
  student_name text not null check (char_length(student_name) between 1 and 100),
  score integer not null check (score between 0 and 100),
  feedback text check (feedback is null or char_length(feedback) <= 500),
  created_at timestamptz not null default now()
);

create table public.feedback (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  rating integer not null check (rating between 1 and 5),
  comment text not null check (char_length(comment) between 1 and 1000),
  created_at timestamptz not null default now()
);

create index students_auth_user_id_idx on public.students(auth_user_id) where auth_user_id is not null;
create index submissions_student_id_idx on public.submissions(student_id);
create index quiz_results_student_id_idx on public.quiz_results(student_id, created_at desc);

create or replace function private.is_teacher()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.user_profiles p
    where p.id = (select auth.uid()) and p.role = 'teacher'
  );
$$;
revoke all on function private.is_teacher() from public, anon;
grant execute on function private.is_teacher() to authenticated;

create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  assigned_role text;
begin
  perform pg_advisory_xact_lock(741029103);
  if exists (select 1 from public.user_profiles p where p.role = 'teacher') then
    assigned_role := 'student';
  else
    assigned_role := 'teacher';
  end if;

  insert into public.user_profiles(id, email, display_name, role)
  values (
    new.id,
    coalesce(new.email, ''),
    coalesce(nullif(left(new.raw_user_meta_data ->> 'display_name', 100), ''), split_part(coalesce(new.email, 'Classroom member'), '@', 1)),
    assigned_role
  );
  return new;
end;
$$;
revoke all on function private.handle_new_user() from public, anon, authenticated;
drop trigger if exists on_auth_user_created_funno on auth.users;
create trigger on_auth_user_created_funno
  after insert on auth.users
  for each row execute function private.handle_new_user();

alter table public.user_profiles enable row level security;
alter table public.students enable row level security;
alter table public.resources enable row level security;
alter table public.assignments enable row level security;
alter table public.submissions enable row level security;
alter table public.quizzes enable row level security;
alter table public.quiz_results enable row level security;
alter table public.feedback enable row level security;

create policy profiles_read_self_or_teacher on public.user_profiles for select to authenticated
  using (id = (select auth.uid()) or (select private.is_teacher()));
create policy profiles_teacher_update on public.user_profiles for update to authenticated
  using ((select private.is_teacher())) with check (role in ('teacher', 'student'));

create policy students_read_own_or_teacher on public.students for select to authenticated
  using (auth_user_id = (select auth.uid()) or (select private.is_teacher()));
create policy students_teacher_insert on public.students for insert to authenticated
  with check ((select private.is_teacher()));
create policy students_teacher_update on public.students for update to authenticated
  using ((select private.is_teacher())) with check ((select private.is_teacher()));
create policy students_teacher_delete on public.students for delete to authenticated
  using ((select private.is_teacher()));

create policy resources_read_class on public.resources for select to authenticated using (true);
create policy resources_teacher_insert on public.resources for insert to authenticated with check ((select private.is_teacher()));
create policy resources_teacher_update on public.resources for update to authenticated using ((select private.is_teacher())) with check ((select private.is_teacher()));
create policy resources_teacher_delete on public.resources for delete to authenticated using ((select private.is_teacher()));

create policy assignments_read_class on public.assignments for select to authenticated using (true);
create policy assignments_teacher_insert on public.assignments for insert to authenticated with check ((select private.is_teacher()));
create policy assignments_teacher_update on public.assignments for update to authenticated using ((select private.is_teacher())) with check ((select private.is_teacher()));
create policy assignments_teacher_delete on public.assignments for delete to authenticated using ((select private.is_teacher()));

create policy submissions_read_own_or_teacher on public.submissions for select to authenticated
  using ((select private.is_teacher()) or exists (
    select 1 from public.students s where s.id = student_id and s.auth_user_id = (select auth.uid())
  ));
create policy submissions_insert_own on public.submissions for insert to authenticated
  with check (exists (select 1 from public.students s where s.id = student_id and s.auth_user_id = (select auth.uid()) and s.name = student_name));
create policy submissions_update_own on public.submissions for update to authenticated
  using (exists (select 1 from public.students s where s.id = student_id and s.auth_user_id = (select auth.uid()) and s.name = student_name))
  with check (exists (select 1 from public.students s where s.id = student_id and s.auth_user_id = (select auth.uid()) and s.name = student_name));
create policy submissions_teacher_delete on public.submissions for delete to authenticated using ((select private.is_teacher()));

create policy quizzes_read_class on public.quizzes for select to authenticated using (true);
create policy quizzes_teacher_insert on public.quizzes for insert to authenticated with check ((select private.is_teacher()));
create policy quizzes_teacher_update on public.quizzes for update to authenticated using ((select private.is_teacher())) with check ((select private.is_teacher()));
create policy quizzes_teacher_delete on public.quizzes for delete to authenticated using ((select private.is_teacher()));

create policy quiz_results_read_own_or_teacher on public.quiz_results for select to authenticated
  using ((select private.is_teacher()) or exists (
    select 1 from public.students s where s.id = student_id and s.auth_user_id = (select auth.uid())
  ));
create policy quiz_results_insert_own on public.quiz_results for insert to authenticated
  with check (exists (select 1 from public.students s where s.id = student_id and s.auth_user_id = (select auth.uid()) and s.name = student_name));
create policy quiz_results_teacher_update on public.quiz_results for update to authenticated
  using ((select private.is_teacher())) with check ((select private.is_teacher()));
create policy quiz_results_teacher_delete on public.quiz_results for delete to authenticated using ((select private.is_teacher()));

create policy feedback_read_own_or_teacher on public.feedback for select to authenticated
  using (user_id = (select auth.uid()) or (select private.is_teacher()));
create policy feedback_insert_own on public.feedback for insert to authenticated
  with check (user_id = (select auth.uid()));
create policy feedback_teacher_delete on public.feedback for delete to authenticated using ((select private.is_teacher()));

grant usage on schema public to authenticated;
grant select, insert, update, delete on
  public.user_profiles, public.students, public.resources, public.assignments,
  public.submissions, public.quizzes, public.quiz_results, public.feedback
  to authenticated;
grant usage, select on all sequences in schema public to authenticated;
revoke all on
  public.user_profiles, public.students, public.resources, public.assignments,
  public.submissions, public.quizzes, public.quiz_results, public.feedback
  from anon;
